/// The end of the first scan's entropy data: the first FF followed by a
/// byte of 0x80 or more that is neither FF fill nor RSTm (T.87 bit stuffing).
pub fn jlsFirstScanEnd(data: []const u8) usize {
    const sos = std.mem.indexOf(u8, data, &.{ 0xff, 0xda }).?;
    var i = sos + 2 + std.mem.readInt(u16, data[sos + 2 ..][0..2], .big);
    while (i + 1 < data.len) : (i += 1) {
        if (data[i] != 0xff) continue;
        const next = data[i + 1];
        if (next < 0x80 or next == 0xff) continue;
        if (next >= 0xd0 and next <= 0xd7) {
            i += 1;
            continue;
        }
        return i;
    }
    unreachable;
}

/// `src` with SOF55 Y set to `y`, and optionally a DNL with NL = `nl`
/// inserted right after the first scan.
pub fn jlsWithDnl(allocator: std.mem.Allocator, src: []const u8, y: u16, nl: ?u16) ![]u8 {
    const at = jlsFirstScanEnd(src);
    const dnl: []const u8 = if (nl) |lines| &.{ 0xff, 0xdc, 0x00, 0x04, @intCast(lines >> 8), @truncate(lines) } else &.{};
    const out = try std.mem.concat(allocator, u8, &.{ src[0..at], dnl, src[at..] });
    const sof = std.mem.indexOf(u8, out, &.{ 0xff, 0xf7 }).?;
    std.mem.writeInt(u16, out[sof + 5 ..][0..2], y, .big);
    return out;
}

/// `src` with the Al (point transform Pt) of every SOS set to `pt`. Only
/// headers are searched: each scan's entropy data is skipped.
pub fn jlsWithPt(allocator: std.mem.Allocator, src: []const u8, pt: u4) ![]u8 {
    const out = try allocator.dupe(u8, src);
    var from: usize = 0;
    while (std.mem.indexOfPos(u8, out, from, &.{ 0xff, 0xda })) |sos| {
        const len = std.mem.readInt(u16, out[sos + 2 ..][0..2], .big);
        const al = sos + 2 + len - 1;
        out[al] = (out[al] & 0xf0) | pt;
        from = sos + jlsFirstScanEnd(out[sos..]);
    }
    return out;
}

pub fn ptSample(x: usize, y: usize) u8 {
    return @intCast(((x * 37 + y * 91) ^ (x * y)) % 128);
}

